export const SETTLEMENT_OFFSET_X = 17;
export const SETTLEMENT_OFFSET_Y = 20;

function generate64Map(withTrails = false) {
  const map = [];
  const baseOriginal = withTrails ? BASE_DIRT_TRAIL_30X24 : BASE_PURE_GRASS_30X24;

  for (let r = 0; r < 64; r++) {
    const row = new Array(64);
    for (let c = 0; c < 64; c++) {
      if (r >= SETTLEMENT_OFFSET_Y && r < SETTLEMENT_OFFSET_Y + 24 &&
          c >= SETTLEMENT_OFFSET_X && c < SETTLEMENT_OFFSET_X + 30) {
        row[c] = baseOriginal[r - SETTLEMENT_OFFSET_Y][c - SETTLEMENT_OFFSET_X];
      } else {
        // Natural eastern coastline extension connecting from settlement beach
        const coastC = 37 + Math.sin(r * 0.12) * 2;
        if (c >= coastC + 3) {
          row[c] = 2; // Water
        } else if (c >= coastC) {
          row[c] = 3; // Sand
        } else {
          row[c] = 0; // Grass
        }
      }
    }
    map.push(row);
  }

  // Extend trails north and south from settlement if trails enabled
  if (withTrails) {
    const carve = (c, r) => {
      const tc = Math.round(c);
      const tr = Math.round(r);
      if (tc >= 0 && tc < 64 && tr >= 0 && tr < 64) {
        if (map[tr][tc] === 0 || map[tr][tc] === 3) {
          map[tr][tc] = 1;
        }
      }
    };

    // Northward trail from house (connects from r=24, c=22)
    for (let r = 24; r >= 6; r--) {
      const c = 22 + Math.sin((24 - r) * 0.15) * 3;
      carve(c, r);
    }

    // Southward trail from settlement (connects from r=36, c=28)
    for (let r = 36; r < 58; r++) {
      const c = 28 + Math.sin((r - 36) * 0.12) * 3;
      carve(c, r);
    }
  }

  return map;
}

export const PURE_GRASS_TERRAIN_MAP = generate64Map(false);
export const DIRT_TRAIL_TERRAIN_MAP = generate64Map(true);
export const DEFAULT_TERRAIN_MAP = PURE_GRASS_TERRAIN_MAP;
